const assert=require('assert'),fs=require('fs');
require('./hex-engine.js');require('./hex-v02.js');require('./hex-v021.js');require('./hex-v022.js');
const H=global.HexEngine,V=global.HexV02,X=global.HexV022;
assert.strictEqual(X.teams.length,30,'all 30 current NBA teams must exist');
assert.strictEqual(X.teams.filter(t=>t.conference==='EAST').length,15);
assert.strictEqual(X.teams.filter(t=>t.conference==='WEST').length,15);
assert.strictEqual(X.historicalPlayers.length,270,'first historical database should contain 270 player versions');
assert.strictEqual(X.validateHistory().errors.length,0,'every pool assignment must match player.teams');
assert(X.teams.every(t=>t.playerPoolIds.length===9),'each team needs a 9-player seed pool');
const league=X.createLeague('HX-0222-TEST','LAL',H,V);
assert.strictEqual(league.length,29,'player controls one of 30 teams');
assert(!league.some(t=>t.id==='LAL'),'AI league cannot duplicate selected team');
assert(league.every(t=>t.roster.length===8&&t.starterIds.length===5&&t.coreIds.length===3&&t.hexIds.length===4));
assert(league.every(t=>t.roster.every(p=>p.teams.includes(t.id))),'AI may only use a player assigned to that real team');
assert.deepStrictEqual(league.map(t=>({id:t.id,roster:t.roster.map(p=>p.id),hex:t.hexIds,cores:t.coreIds,power:t.ratings.power})),X.createLeague('HX-0222-TEST','LAL',H,V).map(t=>({id:t.id,roster:t.roster.map(p=>p.id),hex:t.hexIds,cores:t.coreIds,power:t.ratings.power})),'same seed and selected team must reproduce the league');
const budgets=league.reduce((m,t)=>(m[t.budget]=(m[t.budget]||0)+1,m),{});
assert.deepStrictEqual(budgets,{CONTENDER:6,PLAYOFF:9,AVERAGE:9,REBUILDING:5});
const schedule=X.createSchedule('HX-0222-TEST','LAL',V),lakers=X.teamById('LAL');
assert.strictEqual(schedule.length,82);
assert(schedule.filter(id=>X.teamById(id).conference===lakers.conference).length>schedule.filter(id=>X.teamById(id).conference!==lakers.conference).length,'same-conference opponents should appear more often');
const roster=['curry16','jordan91','durant17','garnett04','hakeem94','klay16','kawhi19','duncan03'].map(id=>H.players.find(p=>p.id===id));
const state={seed:'HX-0222-TEST',selectedTeam:'LAL',leagueTeams:league,schedule,roster,starterIds:roster.slice(0,5).map(p=>p.id),coreIds:roster.slice(0,3).map(p=>p.id),hexIds:['three_rain','switch_everything','share_ball','defense_titles'],season:{games:20,wins:13,losses:7,streak:2,last10:'7-3',stats:{}}};
const snapshot=X.updateLeague(state,20,H,V);
assert.strictEqual(snapshot.length,30);
assert(snapshot.filter(t=>t.conference==='EAST').every(t=>t.rank>=1&&t.rank<=15));
assert(snapshot.filter(t=>t.conference==='WEST').every(t=>t.rank>=1&&t.rank<=15));
assert(Object.keys(X.leaders(state,H)).includes('mvp')&&X.leaders(state,H).scoring.length===5);
const html=fs.readFileSync('./hex.html','utf8'),ui=fs.readFileSync('./hex-ui.js','utf8'),css=fs.readFileSync('./hex-v02.css','utf8');
assert(html.includes('hex-v022.js'));
for(const team of X.teams)assert(fs.existsSync(`./assets/team-logos/${team.id}.svg`),`missing ${team.id} logo`);
assert(ui.includes('renderTeamSelect')&&ui.includes('renderScout')&&ui.includes('renderLeaders')&&ui.includes('WHY YOU'));
assert(ui.includes('contextBack')&&ui.includes('updateTopNavigation'),'secondary screens need contextual back navigation');
assert(!ui.includes('localStorage.clear'),'old saves must never be cleared');
assert(css.includes('@media(max-width:560px)')&&css.includes('.scout-roster'));
new Function(fs.readFileSync('./hex-v022.js','utf8'));new Function(ui);
console.log('V0.2.2 historical league, seed, standings and scouting QA passed.');
